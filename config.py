"""와이파이 서베이 설정. 튜닝할 값은 전부 여기 있다.

노트북은 서버만 하고, **폰 브라우저가 측정기이자 화면**이다.

    폰 브라우저  ──HTTP──>  노트북(이 파일)  탭한 자리에서 지연·속도를 잰다
    폰 브라우저             폰 브라우저      같은 화면에 히트맵을 그린다

결과를 노트북 화면에 안 그리는 이유는 하나다 — **봐야 하는 사람이 집 안을
걸어다니고 있다.** 한 지점 잴 때마다 책상으로 돌아와야 하면 측정 자체가 안 된다.
화면이 손에 들려 있어야 한다.

의존성이 표준 라이브러리뿐이라 가상환경도 설치 과정도 없다.
"""

from dataclasses import dataclass


@dataclass
class WifiConfig:
    # --- 서버 -----------------------------------------------------------
    # 흔히 쓰는 개발 포트(3000, 5000, 8000, 8080)를 피한 번호다. 폰이 못
    # 붙었을 때 원인이 "다른 프로그램이 그 포트를 쥐고 있어서"인 경우를
    # 먼저 지워 두는 편이 낫다. 이미 쓰고 있으면 --port 로 바꾼다.
    port: int = 5010

    # 0.0.0.0 이어야 폰에서 들어올 수 있다. 127.0.0.1 이면 노트북 자신만 된다.
    host: str = "0.0.0.0"

    # 측정 결과를 여기에 쌓는다. 폰 localStorage 에도 사본이 남지만, 폰
    # 브라우저 저장소는 사용자가 캐시를 지우면 같이 날아간다.
    save_path: str = "survey_data.json"

    # --- 지연(RTT) 측정 --------------------------------------------------
    # 빈 응답을 왕복시키고 걸린 시간을 잰다.
    #
    # 중앙값을 쓴다. 평균이 아니라. 앞선 실측에서 이 노트북↔공유기 왕복이
    # 3~48ms 로 튀었는데, 48ms 한 방이 평균을 끌어올려서 "이 자리가 나쁘다"로
    # 읽히게 만든다. 그 48ms 는 자리 탓이 아니라 그 순간 누가 뭘 받고 있던
    # 탓이다. 중앙값은 그런 한 방을 통째로 무시한다.
    ping_count: int = 15

    # 첫 몇 번은 버린다. TCP 연결을 새로 여는 왕복이 섞여 있어서, 자리와
    # 무관하게 첫 값만 크게 나온다.
    ping_warmup: int = 3

    # --- 속도 측정 --------------------------------------------------------
    # "N바이트를 받는 데 걸린 시간"이 아니라 "정해진 시간 동안 받은 바이트"로
    # 잰다. 전자는 느린 자리에서 한없이 길어진다 — 신호가 약한 구석을 재는 게
    # 목적인데 하필 그 자리에서 30초씩 서 있게 된다.
    #
    # 이러면 빠르든 느리든 한 지점이 항상 같은 시간에 끝나서, 집 한 바퀴를
    # 도는 데 걸리는 시간을 미리 계산할 수 있다.
    speed_window_s: float = 1.5

    # 앞부분을 버린다. TCP 슬로우 스타트 때문에 처음 수백 ms 는 링크가
    # 아니라 혼잡제어 알고리즘의 속도를 재게 된다. 여기를 넣으면 실제보다
    # 느리게 나오고, 그 편향이 자리마다 달라서 비교가 망가진다.
    speed_rampup_s: float = 0.4

    # 서버가 한 번에 밀어 넣는 덩어리. 너무 작으면 파이썬 쪽이 병목이 되고
    # (측정하는 게 링크가 아니라 인터프리터가 된다), 너무 크면 정지 시점의
    # 오차가 커진다.
    speed_chunk_bytes: int = 64 * 1024

    # 안전장치. 클라이언트가 죽어도 서버 스레드가 영원히 쏘지 않게.
    speed_max_seconds: float = 20.0

    # --- RSSI (선택) ------------------------------------------------------
    # 브라우저는 신호 세기를 못 읽는다. 웹 표준에 그런 API 가 없다.
    # 안드로이드 폰을 무선 디버깅으로 붙여 두면 노트북에서 adb 로 뽑을 수
    # 있어서, 있으면 쓰고 없으면 조용히 넘어간다.
    #
    # 없어도 서베이는 완결된다. RSSI 는 "안테나에 얼마나 들어오나"고 속도는
    # "그래서 얼마나 되나"인데, 알고 싶은 게 보통 후자다.
    enable_adb_rssi: bool = True
    adb_path: str = "adb"
    adb_timeout_s: float = 3.0

    # --- 히트맵 보간 ------------------------------------------------------
    # IDW (거리 역수 가중). 크리깅은 과하다 — 집 한 채면 측정점이 10~30개고,
    # 그 개수에서는 배리오그램을 추정할 근거 자체가 부족하다.
    idw_power: float = 2.0

    # **가장 가까운 측정점이 이 거리보다 멀면 아예 안 칠한다.** (캔버스
    # 짧은 변에 대한 비율)
    #
    # 이게 없으면 IDW 가 측정 범위 밖을 전체 평균으로 메워서, 재 본 적도 없는
    # 옆집까지 색이 칠해진다. 그 색은 데이터가 아니라 보간 알고리즘의
    # 기본 동작인데, 화면에서는 측정값과 똑같이 생겼다.
    idw_radius_frac: float = 0.22

    # 픽셀마다 계산하면 폰에서 버벅인다. 이 크기의 격자로 계산하고 확대한다.
    # 어차피 보간된 값이라 격자가 조금 거칠어도 잃는 정보가 없다.
    heatmap_cell_px: int = 6
